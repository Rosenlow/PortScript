"""audio/words.json (spoken spelling) -> scenes/main/cues.js
- cue times for the scene, looked up by word prefix (throws if a word is missing)
- caption chunks in DISPLAY spelling (CPL, Ashwagandha, KSM-66)"""
import json, sys, re
src = sys.argv[1] if len(sys.argv) > 1 else "audio/words.json"
W = json.load(open(src, encoding="utf-8"))
low = lambda s: s.replace("I", "ı").replace("İ", "i").lower()
def at(prefix, after=0.0):
    p = low(prefix)
    for x in W:
        if x["s"] >= after - 0.01 and low(re.sub(r'^["“\'«]', "", x["w"])).startswith(p):
            return x["s"]
    raise SystemExit(f"word not found: {prefix} after {after}")
def end_of(prefix, after=0.0):
    s = at(prefix, after)
    return next(x["e"] for x in W if x["s"] == s)
c = {}
c["s1"] = 0.0
c["s2"] = at("yoğun"); c["stres"] = at("stres", c["s2"]); c["yarim"] = at("yarım")
c["s3"] = at("aşvaganda"); c["yuzyil"] = at("yüzyıl"); c["adaptojen"] = at("adaptojen")
c["s4"] = at("si", c["adaptojen"]); c["ksm"] = at("ke", c["s4"]); c["kok"] = at("kök", c["s4"])
c["stresle"] = at("stresle"); c["dinlen"] = at("dinlendirici")
c["s5"] = at("altmış", at("destek")); c["gunluk"] = at("günlük")
c["s6"] = at("si", c["gunluk"]); c["dengeni"] = at("dengeni")
c["voiceEnd"] = W[-1]["e"]
c["end"] = round(c["voiceEnd"] + 2.8, 2)
# display spelling for captions
disp, i = [], 0
while i < len(W):
    w = W[i]["w"]; nxt = [x["w"] for x in W[i:i+5]]
    if [low(x).strip(",.") for x in nxt[:3]] == ["si", "pi", "el"]:
        disp.append({"w": "CPL" + W[i+2]["w"][2:], "s": W[i]["s"], "e": W[i+2]["e"]}); i += 3; continue
    if [low(x).strip(",.") for x in nxt[:5]] == ["ke", "se", "me", "altmış", "altı"]:
        disp.append({"w": "KSM-66", "s": W[i]["s"], "e": W[i+4]["e"]}); i += 5; continue
    if low(w).startswith("aşvaganda"):
        w = "Ashwagandha" + w[len("Aşvaganda"):]
    disp.append({"w": w, "s": W[i]["s"], "e": W[i]["e"]}); i += 1
# chunks: per sentence, n = ceil(chars/24) balanced pieces, never a lone last word
import math
sents, cur = [], []
for x in disp:
    cur.append(x)
    if x["w"][-1] in ".?!": sents.append(cur); cur = []
if cur: sents.append(cur)
chunks = []
from itertools import combinations
def cost(parts):
    lens = [len(" ".join(y["w"] for y in q)) for q in parts]
    c = max(lens) + (100 if max(lens) > 26 else 0)
    c += sum(40 for q in parts if len(q) == 1 and len(parts) > 1)       # lone words
    c -= sum(6 for q in parts[:-1] if q[-1]["w"].endswith(","))         # prefer comma breaks
    return c
for se in sents:
    L = len(" ".join(y["w"] for y in se)); best = None
    for n in (max(1, math.ceil(L / 24)), max(1, math.ceil(L / 24)) + 1):
        for cuts in combinations(range(1, len(se)), n - 1):
            b = (0,) + cuts + (len(se),)
            parts = [se[b[i]:b[i+1]] for i in range(n)]
            if best is None or cost(parts) < best[0]: best = (cost(parts), parts)
        if best[0] < 100: break
    for q in best[1]: chunks.append({"words": q, "s": q[0]["s"], "_se": se})
for ch in chunks: ch.pop("_se")
for j, ch in enumerate(chunks):
    ch["e"] = chunks[j+1]["s"] if j + 1 < len(chunks) else c["voiceEnd"] + 0.3
json.dump(chunks, open("audio/captions.chunks.json", "w", encoding="utf-8"), ensure_ascii=False)
open("scenes/main/cues.js", "w", encoding="utf-8").write(
    "// generated by build/make_cues.py from " + src + " (do not edit by hand)\n"
    "window.CUES = " + json.dumps(c) + ";\nwindow.CHUNKS = " + json.dumps(chunks, ensure_ascii=False) + ";\n")
print(json.dumps(c)); print(len(chunks), "chunks:", [" ".join(w["w"] for w in ch["words"]) for ch in chunks])

tpl = open("build/index.template.html", encoding="utf-8").read()
open("scenes/main/index.html", "w", encoding="utf-8").write(tpl.replace("__DUR__", str(c["end"])))
print("index.html duration", c["end"])
open("audio/duration.txt","w").write(str(c["end"]))
