"""audio/words.json (spoken spelling) -> scenes/main/cues.js + audio/captions.chunks.json + scenes/main/index.html
- cue times looked up by word prefix (throws if a word is missing)
- caption chunks in DISPLAY spelling: 110, BDNF, %99,237, Semax (clinical), N-Acetyl Semax (product), Janoshik"""
import json, sys, re, math
from itertools import combinations
src = sys.argv[1] if len(sys.argv) > 1 else "audio/words.json"
W = json.load(open(src, encoding="utf-8"))
low = lambda s: s.replace("I", "ı").replace("İ", "i").lower()
def at(prefix, after=0.0):
    p = low(prefix)
    for x in W:
        if x["s"] >= after - 0.01 and low(x["w"]).startswith(p): return x["s"]
    raise SystemExit(f"word not found: {prefix} after {after}")
def end_of(prefix, after=0.0):
    s = at(prefix, after); return next(x["e"] for x in W if x["s"] == s)
c = {"s1": 0.0}
c["rehab"] = round(at("bir") - 0.22, 3); c["n110"] = at("yüz", c["rehab"]); c["izledi"] = at("izledi")
c["lab"] = round(at("kanda") - 0.2, 3)
c["tube"] = round(at("bu", c["lab"]) - 0.18, 3)
c["adi"] = at("adı"); c["bdnf"] = at("bi", c["adi"])
c["finding"] = round(at("semaks", c["bdnf"]) - 0.15, 3); c["yukseldi"] = at("yükseldi")
c["prod"] = round(at("peki") - 0.25, 3); c["nacetyl"] = at("n-asetil")
c["report"] = round(at("janoşik") - 0.3, 3); c["saflik"] = at("saflığı"); c["yuzde"] = at("yüzde", c["report"])
c["otuz"] = at("otuz"); c["raporladi"] = at("raporladı")
c["voiceEnd"] = W[-1]["e"]
c["end"] = round(c["voiceEnd"] + 2.2, 2)
RULES = [(["yüz", "on"], "110"), (["bi", "di", "en", "ef"], "BDNF"),
         (["yüzde", "doksan", "dokuz", "virgül", "iki", "yüz", "otuz", "yedi"], "%99,237"),
         (["n-asetil", "semaks"], "N-Acetyl Semax")]
disp, i = [], 0
while i < len(W):
    hit = None
    for toks, out in RULES:
        if [low(x["w"]).strip(",.:?") for x in W[i:i+len(toks)]] == toks: hit = (toks, out); break
    if hit:
        n = len(hit[0]); tail = re.sub(r"^.*?([,.:?]*)$", r"\1", W[i+n-1]["w"])
        disp.append({"w": hit[1] + tail, "s": W[i]["s"], "e": W[i+n-1]["e"]}); i += n; continue
    w = W[i]["w"]
    if low(w).startswith("semaks"): w = "Semax" + w[len("Semaks"):]
    if low(w).startswith("janoşik"): w = "Janoshik" + w[len("Janoşik"):]
    disp.append({"w": w, "s": W[i]["s"], "e": W[i]["e"]}); i += 1
sents, cur = [], []
for x in disp:
    cur.append(x)
    if x["w"][-1] in ".?!": sents.append(cur); cur = []
if cur: sents.append(cur)
def cost(parts):
    lens = [len(" ".join(y["w"] for y in q)) for q in parts]
    c_ = max(lens) + (100 if max(lens) > 26 else 0)
    c_ += sum(40 for q in parts if len(q) == 1 and len(parts) > 1 and len(q[0]["w"]) < 9)
    c_ -= sum(6 for q in parts[:-1] if q[-1]["w"].endswith(","))
    return c_
chunks = []
for se in sents:
    L = len(" ".join(y["w"] for y in se)); best = None
    for n in (max(1, math.ceil(L / 24)), max(1, math.ceil(L / 24)) + 1):
        for cuts in combinations(range(1, len(se)), n - 1):
            b = (0,) + cuts + (len(se),); parts = [se[b[k]:b[k+1]] for k in range(n)]
            if best is None or cost(parts) < best[0]: best = (cost(parts), parts)
        if best[0] < 100: break
    for q in best[1]: chunks.append({"words": q, "s": q[0]["s"]})
for j, ch in enumerate(chunks):
    nxt = chunks[j+1]["s"] if j + 1 < len(chunks) else c["voiceEnd"] + 0.35
    ch["e"] = round(min(nxt, ch["words"][-1]["e"] + 0.6), 3)
json.dump(chunks, open("audio/captions.chunks.json", "w", encoding="utf-8"), ensure_ascii=False)
open("scenes/main/cues.js", "w", encoding="utf-8").write(
    "// generated by build/make_cues.py from " + src + " (do not edit by hand)\n"
    "window.CUES = " + json.dumps(c) + ";\nwindow.CHUNKS = " + json.dumps(chunks, ensure_ascii=False) + ";\n")
print(json.dumps(c)); print(len(chunks), "chunks:", [" ".join(w["w"] for w in ch["words"]) for ch in chunks])
tpl = open("build/index.template.html", encoding="utf-8").read()
open("scenes/main/index.html", "w", encoding="utf-8").write(tpl.replace("__DUR__", str(c["end"])))
open("audio/duration.txt", "w").write(str(c["end"]))
